nums = [3, 1, 4, 2]

nums.sort()
print(f"Orden ascendente: {nums}")

nums.sort(reverse=True)
print(f"Orden descendente: {nums}")

letras = ["c", "a", "b"]

letras.reverse()
print(f"Lista invertida: {letras}")

original = [3, 1, 4, 2]

nueva = sorted(original)
print(f"Lista original: {original}")
print(f"Nueva lista ordenada: {nueva}")